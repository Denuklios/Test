/** Text in der Gerätesprache; {0}, {1} … werden durch [args] ersetzt. */
fun tr(de: String, vararg args: Any?): String {
    var s = if (I18n.german()) de else I18n.en[de] ?: de
    args.forEachIndexed { i, a -> s = s.replace("{$i}", a?.toString() ?: "") }
    return s
}
